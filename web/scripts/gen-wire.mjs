// Turns src/wire/schema.json (exported from server/src/karaoke/contract.py) into src/wire/generated.ts.
// Both outputs are gitignored. They are rebuilt before dev, build, and typecheck, so a Python change to the
// contract shows up as a TypeScript compile error on the page that needs updating, never as a runtime surprise.
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const here = new URL("../src/wire/", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("schema.json", here), "utf8"));

// Pydantic titles every property ("Kind", "Title", ...). json-schema-to-typescript would turn each into its own
// exported alias (Kind, Kind1, Kind2, ...). Only model titles in $defs and the root name a type.
function dropPropertyTitles(node, isNamed) {
  if (Array.isArray(node)) return node.map((n) => dropPropertyTitles(n, false));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && !isNamed) continue;
    if (key === "$defs" || key === "properties") {
      // Map keys here are names (a model, or a field such as `title`), not schema keywords.
      const named = key === "$defs";
      out[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, dropPropertyTitles(v, named)]));
    } else {
      out[key] = dropPropertyTitles(value, false);
    }
  }
  return out;
}

const { "x-protocol": protocol, ...contract } = schema;
if (typeof protocol !== "string") throw new Error("schema.json has no x-protocol; re-run export_schema");

const ts = await compile(dropPropertyTitles(contract, true), "Contract", {
  bannerComment: "/* GENERATED by `npm run gen:wire` from server/src/karaoke/contract.py. DO NOT EDIT. */",
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  additionalProperties: false,
  format: false,
});
const protocolLine = `\n/** Must equal the server's ServerHello.protocol, or the page reloads to fetch the current build. */\nexport const PROTOCOL = ${JSON.stringify(protocol)};\n`;
writeFileSync(new URL("generated.ts", here), ts + protocolLine);
